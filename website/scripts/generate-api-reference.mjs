import { spawnSync } from "node:child_process";
import { readFile, writeFile, mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const websiteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const requiredSchemas = ["error_response", "event", "request", "response", "subscription_event"];
const generatedNotice = "{/* Generated by scripts/generate-api-reference.mjs. Do not edit. */}";
/**
 * Generated schemas are arbitrary JSON Schema documents. Their shape is validated at runtime.
 * @typedef {Record<string, any>} SchemaNode
 */

/**
 * @param {string} message
 * @returns {never}
 */
function fail(message) {
  throw new Error(`Local API reference generation failed: ${message}`);
}

/** @param {string[]} argv */
function parseArgs(argv) {
  /** @type {{ binary?: string, schema?: string, root: string, publishLatest: boolean, check: boolean }} */
  const options = {
    binary: process.env.GARDN_API_BINARY,
    schema: undefined,
    root: websiteRoot,
    publishLatest: false,
    check: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--binary" || argument === "--schema" || argument === "--root") {
      const value = argv[index + 1];
      if (!value) fail(`${argument} requires a value`);
      if (argument === "--binary") options.binary = value;
      if (argument === "--schema") options.schema = value;
      if (argument === "--root") options.root = value;
      index += 1;
    } else if (argument === "--publish-latest") {
      options.publishLatest = true;
    } else if (argument === "--check") {
      options.check = true;
    } else {
      fail(`unknown option ${argument}`);
    }
  }

  if (options.binary && options.schema) fail("use either --binary or --schema, not both");
  const root = path.resolve(options.root);
  return {
    ...options,
    root,
    schema: options.schema ?? path.join(root, ".generated", "api", "schema.json"),
  };
}

/** @param {string} binary */
function readSchemaFromBinary(binary) {
  const result = spawnSync(path.resolve(binary), ["api", "schema", "--json"], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) fail(`cannot execute ${binary}: ${result.error.message}`);
  if (result.status !== 0) {
    fail(`${binary} exited with ${result.status}: ${result.stderr.trim() || "no error output"}`);
  }
  try {
    return JSON.parse(result.stdout);
  } catch (error) {
    fail(`${binary} returned invalid JSON: ${error instanceof Error ? error.message : error}`);
  }
}

/** @param {string} filename */
async function readSchemaFile(filename) {
  let content = "";
  try {
    content = await readFile(filename, "utf8");
  } catch (error) {
    fail(`cannot read ${filename}: ${error instanceof Error ? error.message : error}`);
  }
  try {
    return JSON.parse(content);
  } catch (error) {
    fail(`${filename} contains invalid JSON: ${error instanceof Error ? error.message : error}`);
  }
}

/** @param {SchemaNode} schema */
function validateSchema(schema) {
  if (!schema || typeof schema !== "object" || Array.isArray(schema))
    fail("schema root must be an object");
  if (!/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(schema.product_version ?? "")) {
    fail("schema is missing a valid product_version");
  }
  if (!Number.isInteger(schema.protocol) || schema.protocol < 1)
    fail("schema is missing a valid protocol");
  if (!Number.isInteger(schema.schema_version) || schema.schema_version < 1) {
    fail("schema is missing a valid schema_version");
  }
  if (!schema.schemas || typeof schema.schemas !== "object") fail("schema is missing schemas");
  for (const name of requiredSchemas) {
    if (!schema.schemas[name]) fail(`schema is missing schemas.${name}`);
  }

  const requestVariants = schema.schemas.request.oneOf;
  if (!Array.isArray(requestVariants) || requestVariants.length === 0) {
    fail("request schema has no method variants");
  }
  const methods = new Set();
  for (const variant of requestVariants) {
    const method = variant?.properties?.method?.const;
    if (typeof method !== "string" || method.length === 0)
      fail("request variant is missing a method name");
    if (methods.has(method)) fail(`request method ${method} is duplicated`);
    methods.add(method);
    if (variant?.properties?.id?.type !== "string" || !variant?.required?.includes("id")) {
      fail(`request method ${method} does not require a string id`);
    }
  }

  const serialized = JSON.stringify(schema);
  for (const internalName of [
    "ClientMessage",
    "ServerMessage",
    "SemanticFrame",
    "HandoffManifest",
  ]) {
    if (serialized.includes(`"${internalName}"`)) {
      fail(`internal client/server contract ${internalName} leaked into the Local API schema`);
    }
  }
}

/**
 * @param {any} value
 * @returns {any}
 */
function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, canonicalize(value[key])]),
    );
  }
  return value;
}

/** @param {SchemaNode} schema */
function schemaJson(schema) {
  return `${JSON.stringify(canonicalize(schema), null, 2)}\n`;
}

/** @param {SchemaNode | undefined} node */
function refName(node) {
  return typeof node?.$ref === "string" ? node.$ref.split("/").at(-1) : undefined;
}

/**
 * @param {SchemaNode | undefined} node
 * @returns {string}
 */
function typeName(node) {
  if (!node) return "unknown";
  const reference = refName(node);
  if (reference) return reference;
  if (Array.isArray(node.type)) return node.type.join(" | ");
  if (node.type === "array") return `${typeName(node.items)}[]`;
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (node.enum)
    return /** @type {unknown[]} */ (node.enum).map((value) => JSON.stringify(value)).join(" | ");
  if (node.oneOf || node.anyOf) return (node.oneOf ?? node.anyOf).map(typeName).join(" | ");
  return node.type ?? "unknown";
}

/** @param {unknown} value */
function escapeCell(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");
}

/**
 * @param {SchemaNode | undefined} definition
 * @param {SchemaNode} defs
 */
function propertyTable(definition, defs) {
  const reference = refName(definition);
  const resolved = reference ? defs[reference] : definition;
  const properties = resolved?.properties;
  if (!properties || Object.keys(properties).length === 0) return "No properties.\n";
  const required = new Set(resolved.required ?? []);
  const rows = Object.entries(properties).map(([name, property]) => {
    const description = property.description ?? "";
    return `| \`${escapeCell(name)}\` | \`${escapeCell(typeName(property))}\` | ${required.has(name) ? "yes" : "no"} | ${escapeCell(description)} |`;
  });
  return [
    "| Property | Type | Required | Description |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

/**
 * @param {string} title
 * @param {string} description
 */
function frontmatter(title, description) {
  return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n${generatedNotice}\n\n`;
}

/** @param {SchemaNode} schema */
function renderOverview(schema) {
  const version = schema.product_version;
  return `${frontmatter("Generated Local API reference", `Generated Local API shapes for Gardn ${version}.`)}# Generated Local API reference\n\nThis reference was generated from the Gardn ${version} binary. It describes JSON shapes, not an HTTP or OpenAPI interface.\n\n| Metadata | Value |\n| --- | --- |\n| Product version | \`${version}\` |\n| Client wire compatibility protocol | \`${schema.protocol}\` |\n| Local API schema version | \`${schema.schema_version}\` |\n\n[Download the immutable JSON Schema for ${version}](/api/${version}/schema.json).\n\nUse the authored [Local API overview](/docs/api) for transport, lifecycle, trust, compatibility, and error semantics.\n`;
}

/** @param {SchemaNode} schema */
function renderRequests(schema) {
  const root = schema.schemas.request;
  const defs = root.$defs ?? {};
  const variants = /** @type {SchemaNode[]} */ (root.oneOf);
  const parameterDefinitions = new Set();
  const sections = variants.map((variant) => {
    const method = variant.properties.method.const;
    const params = variant.properties.params;
    const paramsName = refName(params) ?? typeName(params);
    if (refName(params)) parameterDefinitions.add(paramsName);
    return `## \`${method}\`\n\nParameters: \`${paramsName}\`\n\n${propertyTable(params, defs)}`;
  });
  const dataTypes = dataTypeSections(defs, parameterDefinitions);
  const dataTypeReference =
    dataTypes.length > 0 ? `\n## Data types\n\n${dataTypes.join("\n")}` : "";
  return `${frontmatter("Requests", "Generated Local API request methods and parameter shapes.")}# Requests\n\nEvery request requires a caller-selected string \`id\`, a \`method\`, and the method's \`params\` object. The response echoes the same \`id\`.\n\n${sections.join("\n")}${dataTypeReference}`;
}

/** @param {SchemaNode | undefined} definition */
function unionReferences(definition) {
  return (definition?.oneOf ?? definition?.anyOf ?? []).map(refName).filter(Boolean);
}

/** @param {SchemaNode} variant @param {SchemaNode} defs */
function variantName(variant, defs) {
  const reference = refName(variant);
  const resolved = reference ? defs[reference] : variant;
  return resolved?.properties?.type?.const ?? reference ?? resolved?.title ?? typeName(resolved);
}

/** @param {SchemaNode} definition @param {SchemaNode} defs */
function definitionBody(definition, defs) {
  if (definition?.properties && Object.keys(definition.properties).length > 0) {
    return propertyTable(definition, defs);
  }
  /** @type {SchemaNode[] | undefined} */
  const variants = definition?.oneOf ?? definition?.anyOf;
  if (variants) {
    return `Variants:\n\n${variants.map((variant) => `- \`${escapeCell(variantName(variant, defs))}\``).join("\n")}\n`;
  }
  return `Type: \`${escapeCell(typeName(definition))}\`\n`;
}

/**
 * @param {SchemaNode} defs
 * @param {Set<string>} excluded
 */
function dataTypeSections(defs, excluded) {
  return Object.entries(defs)
    .filter(([name, definition]) => !excluded.has(name) && !Array.isArray(definition.enum))
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, definition]) => `### \`${name}\`\n\n${definitionBody(definition, defs)}`);
}

/**
 * @param {SchemaNode | undefined} definition
 * @param {SchemaNode} defs
 * @returns {string[]}
 */
function unionSections(definition, defs) {
  /** @type {SchemaNode[]} */
  const variants = definition?.oneOf ?? definition?.anyOf ?? [];
  return variants.map((variant) => {
    const reference = refName(variant);
    const resolved = reference ? defs[reference] : variant;
    return `## \`${variantName(variant, defs)}\`\n\n${propertyTable(resolved, defs)}`;
  });
}

/**
 * @param {string} title
 * @param {string} description
 * @param {SchemaNode[]} roots
 * @param {string[]} preferredUnions
 */
function renderDefinitions(title, description, roots, preferredUnions = []) {
  const sections = [];
  const seen = new Set();
  const dataTypes = [];
  const dataTypeNames = new Set();
  for (const root of roots) {
    const defs = root.$defs ?? {};
    const excluded = new Set(preferredUnions);
    for (const unionName of preferredUnions) {
      const union = defs[unionName];
      for (const name of unionReferences(union)) excluded.add(name);
      for (const section of unionSections(union, defs)) {
        const heading = section.split("\n", 1)[0];
        if (seen.has(heading)) continue;
        seen.add(heading);
        sections.push(section);
      }
    }
    for (const section of dataTypeSections(defs, excluded)) {
      const heading = section.split("\n", 1)[0];
      if (dataTypeNames.has(heading)) continue;
      dataTypeNames.add(heading);
      dataTypes.push(section);
    }
    if (sections.length === 0) {
      sections.push(`## \`${root.title ?? title}\`\n\n${propertyTable(root, defs)}`);
    }
  }
  const dataTypeReference =
    dataTypes.length > 0 ? `\n## Data types\n\n${dataTypes.join("\n")}` : "";
  return `${frontmatter(title, description)}# ${title}\n\n${sections.join("\n")}${dataTypeReference}`;
}

/** @param {SchemaNode} schema */
function renderEvents(schema) {
  const event = schema.schemas.event;
  const subscription = schema.schemas.subscription_event;
  return renderDefinitions(
    "Events",
    "Generated operational and subscription event shapes.",
    [event, subscription],
    ["EventData", "SubscriptionEventData"],
  );
}

/** @param {SchemaNode} schema */
function renderResponses(schema) {
  return renderDefinitions(
    "Responses",
    "Generated successful Local API response result shapes.",
    [schema.schemas.response],
    ["ResponseResult"],
  );
}

/** @param {SchemaNode} schema */
function renderErrors(schema) {
  const root = schema.schemas.error_response;
  return `${frontmatter("Errors", "Generated Local API error response shape.")}# Errors\n\nAn error response echoes the request \`id\` and contains an error code and message. See [error semantics](/docs/api/errors) for lifecycle and recovery guidance.\n\n${propertyTable(root, root.$defs ?? {})}\n## \`ErrorBody\`\n\n${propertyTable(root.$defs?.ErrorBody, root.$defs ?? {})}`;
}

/** @param {SchemaNode} schema */
function renderEnums(schema) {
  /** @type {Map<string, unknown[]>} */
  const enums = new Map();
  for (const root of Object.values(schema.schemas)) {
    for (const [name, definition] of Object.entries(root.$defs ?? {})) {
      if (Array.isArray(definition.enum)) enums.set(name, definition.enum);
    }
  }
  const sections = [...enums.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([name, values]) =>
        `## \`${name}\`\n\n${values.map((value) => `- \`${JSON.stringify(value)}\``).join("\n")}\n`,
    );
  return `${frontmatter("Enums", "Generated Local API enum values.")}# Enums\n\n${sections.join("\n")}`;
}

/**
 * @param {SchemaNode} schema
 * @param {string} root
 * @returns {Map<string, string>}
 */
function generatedFiles(schema, root) {
  const version = schema.product_version;
  const docsRoot = path.join(root, "content", "docs", "api", "reference", "generated");
  const canonical = schemaJson(schema);
  return new Map([
    [path.join(root, ".generated", "api", "schema.json"), canonical],
    [path.join(root, "public", "api", version, "schema.json"), canonical],
    [
      path.join(docsRoot, "meta.json"),
      `${JSON.stringify({ title: "Shape reference", pages: ["index", "requests", "responses", "events", "errors", "enums"] }, null, 2)}\n`,
    ],
    [path.join(docsRoot, "index.mdx"), renderOverview(schema)],
    [path.join(docsRoot, "requests.mdx"), renderRequests(schema)],
    [path.join(docsRoot, "responses.mdx"), renderResponses(schema)],
    [path.join(docsRoot, "events.mdx"), renderEvents(schema)],
    [path.join(docsRoot, "errors.mdx"), renderErrors(schema)],
    [path.join(docsRoot, "enums.mdx"), renderEnums(schema)],
  ]);
}

/**
 * @param {string} filename
 * @param {string} content
 */
async function assertVersionIsImmutable(filename, content) {
  let current;
  try {
    current = await readFile(filename, "utf8");
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") return;
    fail(
      `cannot read immutable schema ${filename}: ${error instanceof Error ? error.message : error}`,
    );
  }
  if (current !== content) {
    fail(
      `${filename} already contains a different schema; bump the Gardn product version instead of replacing a versioned contract`,
    );
  }
}

/**
 * @param {string} filename
 * @param {string} content
 * @param {boolean} check
 */
async function assertOrWrite(filename, content, check) {
  if (check) {
    let current;
    try {
      current = await readFile(filename, "utf8");
    } catch {
      fail(
        `${path.relative(websiteRoot, filename)} is missing; regenerate from the release binary`,
      );
    }
    if (current !== content) {
      fail(`${path.relative(websiteRoot, filename)} is stale; regenerate from the release binary`);
    }
    return;
  }
  await mkdir(path.dirname(filename), { recursive: true });
  await writeFile(filename, content, "utf8");
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const schema = options.binary
    ? readSchemaFromBinary(options.binary)
    : await readSchemaFile(path.resolve(options.schema));
  validateSchema(schema);
  if (options.publishLatest) {
    if (process.env.GARDN_API_RELEASE !== "1") {
      fail("--publish-latest requires GARDN_API_RELEASE=1 from the release deployment");
    }
    const releaseRef = process.env.GITHUB_REF_NAME;
    if (releaseRef && releaseRef !== `v${schema.product_version}`) {
      fail(`release ref ${releaseRef} does not match product version v${schema.product_version}`);
    }
  }

  const files = generatedFiles(schema, options.root);
  const immutableSchema = path.join(
    options.root,
    "public",
    "api",
    schema.product_version,
    "schema.json",
  );
  await assertVersionIsImmutable(immutableSchema, schemaJson(schema));

  const docsRoot = path.join(options.root, "content", "docs", "api", "reference", "generated");
  if (!options.check) await rm(docsRoot, { recursive: true, force: true });
  for (const [filename, content] of files) {
    await assertOrWrite(filename, content, options.check);
  }

  if (options.publishLatest) {
    await assertOrWrite(
      path.join(options.root, "public", "api", "latest", "schema.json"),
      schemaJson(schema),
      options.check,
    );
  }

  console.log(
    `${options.check ? "checked" : "generated"} Local API reference for Gardn ${schema.product_version}`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
